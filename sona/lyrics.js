export function forgeLyrics(seed, mood, dur) {
  const pool = FORGE_LINES[mood] || FORGE_LINES.calm;
  const n = Math.min(pool.length, Math.max(4, Math.floor(dur / 30)));
  const lines = [];
  const gap = Math.floor((dur - 30) / n);
  for (let i = 0; i < n; i++) {
    lines.push({ t: 5 + i * gap, line: pool[(seed + i * 7) % pool.length] });
  }
  return lines;
}
